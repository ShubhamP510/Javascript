// Example of Assignment Operators in JavaScript

let x = 10; // Simple assignment
console.log("Initial value of x:", x);

x += 5; // Addition assignment (x = x + 5)
console.log("After x += 5:", x);

x -= 3; // Subtraction assignment (x = x - 3)
console.log("After x -= 3:", x);

x *= 2; // Multiplication assignment (x = x * 2)
console.log("After x *= 2:", x);

x /= 4; // Division assignment (x = x / 4)
console.log("After x /= 4:", x);

x %= 3; // Remainder assignment (x = x % 3)
console.log("After x %= 3:", x);

x **= 2; // Exponentiation assignment (x = x ** 2)
console.log("After x **= 2:", x);



// Example of Comparison Operators in JavaScript

let a = 10, b = 20;

console.log("a == b:", a == b); // Equal to
console.log("a != b:", a != b); // Not equal to
console.log("a === b:", a === b); // Strict equal to
console.log("a !== b:", a !== b); // Strict not equal to
console.log("a > b:", a > b); // Greater than
console.log("a < b:", a < b); // Less than
console.log("a >= b:", a >= b); // Greater than or equal to
console.log("a <= b:", a <= b); // Less than or equal to